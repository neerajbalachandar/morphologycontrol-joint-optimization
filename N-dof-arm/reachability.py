import numpy as np
from scipy.linalg import expm
from scipy.linalg import eig
from scipy.spatial import ConvexHull


def norm_radius(p, n_inputs, horizon, convention="peak_equivalent"):
    """Lp radius in the paper's integral norm convention.

    Peak-equivalent normalization sets the RMS actuator-normalized magnitude
    across all inputs and time to one: c_p=(N*T)**(1/p). Raw paper mode uses
    c_p=1. L-infinity always uses the unit peak box.
    """
    if np.isinf(p):
        return 1.0
    if p <= 1 or horizon <= 0 or n_inputs < 1:
        raise ValueError("Require p>1, positive horizon, and at least one input.")
    if convention == "raw_paper":
        return 1.0
    if convention == "peak_equivalent":
        return float((n_inputs * horizon) ** (1.0 / p))
    raise ValueError("convention must be 'raw_paper' or 'peak_equivalent'.")


def output_scaling(total_length, horizon):
    """Map physical [x_EE, xdot_EE] to [x/L0, T*xdot/L0]."""
    if total_length <= 0 or horizon <= 0:
        raise ValueError("Length and horizon must be positive.")
    return np.diag([1.0 / total_length, horizon / total_length])


def reachability_kernel(A, B, C, tau_max, T, nt, nondimensionalizer=None):
    """Sample G(t)=S C exp(A(T-t)) B diag(tau_max) for unit inputs."""
    if nt < 2:
        raise ValueError("At least two time samples are required.")
    n_inputs = B.shape[1]
    S = np.eye(C.shape[0]) if nondimensionalizer is None else np.asarray(nondimensionalizer)
    times = np.linspace(0.0, T, nt)
    Dtau = np.diag(np.asarray(tau_max, dtype=float))
    kernels = np.empty((nt, S.shape[0], n_inputs))
    eigenvalues, eigenvectors = eig(A)
    condition = np.linalg.cond(eigenvectors)
    if np.isfinite(condition) and condition < 1e10:
        modal_map = S @ C @ eigenvectors
        modal_input = np.linalg.solve(eigenvectors, B @ Dtau)
        exponentials = np.exp(np.outer(T - times, eigenvalues))
        kernels[:] = np.real(np.einsum("ka,da,ai->kdi", exponentials, modal_map, modal_input))
    else:
        for k, time in enumerate(times):
            kernels[k] = S @ C @ expm(A * (T - time)) @ B @ Dtau
    return times, kernels


def lp_support(theta, kernels, times, p, radius=1.0):
    """Support of projected reachable set for an Lp-bounded normalized input."""
    s = np.array([np.cos(theta), np.sin(theta)])
    projections = np.einsum("tki,k->ti", kernels, s)
    if np.isinf(p):
        values = np.sum(np.abs(projections), axis=1)
    else:
        q = p / (p - 1.0)
        values = np.sum(np.abs(projections) ** q, axis=1) ** (1.0 / q)
    return float(radius * np.trapezoid(values, times))


def lp_support_samples(kernels, times, p, radius=1.0, ntheta=240):
    """Evaluate directional support over evenly spaced unit directions."""
    theta = np.linspace(0.0, 2.0 * np.pi, ntheta, endpoint=False)
    directions = np.column_stack((np.cos(theta), np.sin(theta)))
    projected = np.einsum("tki,dk->tdi", kernels, directions)
    if np.isinf(p):
        directional_norm = np.sum(np.abs(projected), axis=2)
    else:
        q = p / (p - 1.0)
        directional_norm = np.sum(np.abs(projected) ** q, axis=2) ** (1.0 / q)
    support = radius * np.trapezoid(directional_norm, times, axis=0)
    return theta, support


def lp_boundary_points(kernels, times, p, radius=1.0, ntheta=240):
    """Return terminal output points generated by the extremizing Lp inputs."""
    theta = np.linspace(0.0, 2.0 * np.pi, ntheta, endpoint=False)
    points = np.empty((ntheta, kernels.shape[1]))
    dt_weights = np.empty_like(times)
    dt_weights[0] = (times[1] - times[0]) / 2
    dt_weights[-1] = (times[-1] - times[-2]) / 2
    dt_weights[1:-1] = (times[2:] - times[:-2]) / 2
    for k, angle in enumerate(theta):
        s = np.array([np.cos(angle), np.sin(angle)])
        a = np.einsum("tki,k->ti", kernels, s)
        if np.isinf(p):
            control = np.sign(a)
        else:
            q = p / (p - 1.0)
            Hq = np.trapezoid(np.sum(np.abs(a) ** q, axis=1), times)
            H = max(float(Hq), np.finfo(float).tiny) ** (1.0 / q)
            control = radius * H ** (1.0 - q) * np.sign(a) * np.abs(a) ** (q - 1.0)
        points[k] = np.einsum("tki,ti,t->k", kernels, control, dt_weights)
    return theta, points


def convex_hull_area(points):
    """Convex hull area of sampled reachable output points."""
    points = np.asarray(points, dtype=float)
    if len(points) < 3 or not np.all(np.isfinite(points)):
        return 0.0
    try:
        return float(ConvexHull(points).volume)
    except Exception:
        return 0.0


def lp_reachable_set(A, B, C, tau_max, T, p, convention="peak_equivalent",
                     total_length=1.0, ntheta=240, nt=400,
                     nondimensional=True):
    """Return support and an extremizer-generated convex hull in output space.

    In normalized mode, geometry uses (x_EE/L0, T*xdot_EE/L0). Physical
    coordinates can be retained by setting nondimensional=False.
    """
    S = output_scaling(total_length, T) if nondimensional else np.eye(C.shape[0])
    times, kernels = reachability_kernel(A, B, C, tau_max, T, nt, S)
    radius = norm_radius(p, B.shape[1], T, convention)
    theta, support = lp_support_samples(kernels, times, p, radius, ntheta)
    _, points = lp_boundary_points(kernels, times, p, radius, ntheta)
    area = convex_hull_area(points)
    gramian = np.trapezoid(kernels @ np.swapaxes(kernels, 1, 2), times, axis=0)
    if p == 2:
        ellipsoid_area = float(np.pi * radius**2 * np.sqrt(max(np.linalg.det(gramian), 0.0)))
    else:
        ellipsoid_area = None
    return {
        "theta": theta,
        "support": support,
        "boundary": points,
        "area": area,
        "gramian": gramian,
        "ellipsoid_area": ellipsoid_area,
        "times": times,
        "kernels": kernels,
        "radius": radius,
        "p": float(p),
        "convention": convention,
        "nondimensional": bool(nondimensional),
    }


def support_function(theta, A, B, C, tau_max, T=2.0, nt=300):
    """Support function of the projected bounded-input reachable set.

    |u_i(t)| <= tau_max[i]

    h(theta) =
        integral_0^T sum_i tau_i,max
        |c(theta)^T C exp(A(T-t)) b_i| dt
    """
    c = np.array([np.cos(theta), np.sin(theta)])
    t = np.linspace(0.0, T, nt)
    values = np.zeros(nt)

    for k, tk in enumerate(t):
        G = C @ expm(A * (T - tk)) @ B
        values[k] = np.sum(tau_max * np.abs(c @ G))

    return np.trapezoid(values, t)


def reachable_boundary(
    A, B, C, tau_max, T=2.0, ntheta=180, nt=300
):
    theta = np.linspace(
        0.0, 2.0 * np.pi, ntheta, endpoint=False
    )
    # Compute the matrix exponential once per quadrature time. Computing it
    # inside every direction made each design evaluation ntheta times slower.
    t = np.linspace(0.0, T, nt)
    responses = np.array([
        C @ expm(A * (T - tk)) @ B for tk in t
    ])
    directions = np.column_stack((np.cos(theta), np.sin(theta)))
    projections = np.einsum("di,tij->tdj", directions, responses)
    weighted_support = np.sum(
        np.abs(projections) * np.asarray(tau_max)[None, None, :], axis=2
    )
    h = np.trapezoid(weighted_support, t, axis=0)
    return theta, h


def support_to_boundary(theta, h):
    """Recover a smooth convex boundary from sampled support values."""
    dtheta = theta[1] - theta[0]
    h_periodic = np.r_[h[-1], h, h[0]]

    dh = (
        h_periodic[2:] - h_periodic[:-2]
    ) / (2.0 * dtheta)

    normal = np.column_stack([
        np.cos(theta),
        np.sin(theta),
    ])
    tangent = np.column_stack([
        -np.sin(theta),
        np.cos(theta),
    ])

    return h[:, None] * normal + dh[:, None] * tangent


def polygon_area(points):
    x = points[:, 0]
    y = points[:, 1]
    return 0.5 * abs(
        np.sum(
            x * np.roll(y, -1)
            - y * np.roll(x, -1)
        )
    )


def reachable_set(
    A, B, C, tau_max, T=2.0, ntheta=180, nt=300
):
    """Compatibility API for the original dimensional support-boundary area.

    New experiments should use ``lp_reachable_set`` so that the area is based
    on extremizing controls and common nondimensional output coordinates.
    """
    theta, h = reachable_boundary(
        A, B, C, tau_max,
        T=T, ntheta=ntheta, nt=nt
    )
    boundary = support_to_boundary(theta, h)
    area = polygon_area(boundary)
    return theta, h, boundary, area


def output_controllability_gramian(A, B, C, T=2.0, nt=300):
    """Finite-horizon Gramian for the selected output y(T)=C x(T).

    This is the unit-energy reachable ellipsoid matrix. It is distinct from
    the bounded-torque reachable set used by ``reachable_set``.
    """
    t = np.linspace(0.0, T, nt)
    integrand = np.empty((nt, C.shape[0], C.shape[0]))
    for k, ti in enumerate(t):
        G = C @ expm(A * ti) @ B
        integrand[k] = G @ G.T
    return np.trapezoid(integrand, t, axis=0)
